import pytest

from text_format_table import (
    ColumnCountMismatchError,
    ColumnOffsets,
    EmptyTableError,
    FormatConfig,
    FormatTable,
    InvalidSignificantFiguresError,
    OutputFormat,
    TableStyle,
    parse_sig_fig_list,
)

ROWS = [["name", "value"], ["a", "1234.5"], ["b", "0.0123"]]


@pytest.mark.parametrize(
    ("text", "expected"),
    [("[1,2,2,4]", [1, 2, 2, 4]), ("1, 2", [1, 2]), ("(3,4)", [3, 4]), ("[5,]", [5]), ("7", [7])],
)
def test_parse_sig_fig_list(text, expected):
    assert parse_sig_fig_list(text) == expected


@pytest.mark.parametrize("text", ["[1,a]", "__import__('os')", "[1,,2]", "[]"])
def test_parse_sig_fig_list_rejects_non_integers(text):
    with pytest.raises(InvalidSignificantFiguresError):
        parse_sig_fig_list(text)


def test_column_offsets():
    offsets = ColumnOffsets()
    offsets.update(0, 3, 2)
    offsets.update(1, 1, 1)
    offsets.update(0, 2, 5)
    assert offsets.left == [3, 1]
    assert offsets.right == [5, 1]
    assert offsets.width(0) == 8


def test_text_table_render():
    table = FormatTable(ROWS, 3)
    assert table.output_format is OutputFormat.TEXT
    expected_lines = [
        "name |    value    \n",
        "------------------ \n",
        "  a  | 1,230.      \n",
        "  b  |     0.012 3 \n",
        "\n\n",
    ]
    assert table.render() == "".join(expected_lines)
    assert str(table) == table.render()


def test_text_table_columns_align_on_decimal_point():
    lines = FormatTable(ROWS, 3).render().splitlines()
    data = lines[2:4]
    assert data[0].index(".") == data[1].index(".")
    assert len({len(line) for line in lines[:4]}) == 1


def test_latex_table_render():
    table = FormatTable(ROWS, 3, latex=True)
    output = table.render()
    assert table.output_format is OutputFormat.LATEX
    assert "\\begin{tabular}{|S|S|}" in output
    assert "{name}" in output
    assert output.rstrip().endswith("%% Table generated by formatTable utility %%")


def test_sflist_as_list_and_string_are_equivalent():
    assert FormatTable(ROWS, sflist=[2, 3]).render() == FormatTable(ROWS, sflist="[2,3]").render()


def test_sf_takes_precedence_over_sflist():
    assert FormatTable(ROWS, 2, sflist=[5, 5]).render() == FormatTable(ROWS, 2).render()


def test_sf_accepts_numeric_string():
    assert FormatTable(ROWS, "3").render() == FormatTable(ROWS, 3).render()


def test_sf_rejects_non_integer_string():
    with pytest.raises(InvalidSignificantFiguresError):
        FormatTable(ROWS, "three")


def test_row_longer_than_sflist_raises_instead_of_dropping_columns():
    with pytest.raises(ColumnCountMismatchError):
        FormatTable(ROWS, sflist=[2])


def test_rows_shorter_than_sflist_are_allowed():
    table = FormatTable([["x", "y"], ["1"]], sflist=[2, 2])
    assert len(table.cells[1]) == 1


def test_tuple_mode_uses_per_value_sig_figs():
    table = FormatTable([[("h", 0)], [(1234.234, 2)]])
    assert table.cells[1][0].value_str == "1,200."


def test_empty_table_raises():
    with pytest.raises(EmptyTableError):
        FormatTable([], 3)


def test_ragged_rows_render():
    output = FormatTable([["a"], ["1", "2"]], 2).render()
    assert "1." in output and "2." in output


def test_rows_per_page_from_config():
    rows = [["h"]] + [[str(i)] for i in range(1, 6)]
    output = FormatTable(rows, 2, config=FormatConfig(rows_per_page=2)).render()
    # header repeated after rows 2, 4 and 6 (count includes the header row)
    assert output.count(" h ") == 4


def test_max_col_width_truncates_text_cells():
    table = FormatTable([["a very long header"], ["1"]], 2, max_col_width=6)
    assert table.cells[0][0].value_str == "a v..."


def test_repr():
    assert repr(FormatTable(ROWS, 3)) == "<FormatTable rows=3 columns=2 format=text>"


def test_table_style_factories():
    assert TableStyle.text(5).header_rule == "----- \n"
    assert TableStyle.latex(2).header.count("S|") == 2
